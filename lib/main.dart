import 'package:firebase_auth/firebase_auth.dart';
import 'package:firebase_core/firebase_core.dart';
import 'package:flutter/material.dart';
import 'package:flutter_riverpod/flutter_riverpod.dart';
import 'package:shared_preferences/shared_preferences.dart';
import 'package:tutomato/app.dart';
import 'package:tutomato/firebase_options.dart'; // generated by `flutterfire configure`
import 'package:tutomato/providers/core_providers.dart';
import 'package:tutomato/services/prefs_service.dart';

Future<void> main() async {
  WidgetsFlutterBinding.ensureInitialized();
  await Firebase.initializeApp(options: DefaultFirebaseOptions.currentPlatform);

  final prefs = await SharedPreferences.getInstance();

  // "Remember me" unchecked: don't keep the user logged in across app launches.
  final remember = prefs.getBool(PrefsService.rememberMeKey) ?? true;
  if (!remember && FirebaseAuth.instance.currentUser != null) {
    await FirebaseAuth.instance.signOut();
  }

  runApp(
    ProviderScope(
      overrides: [sharedPreferencesProvider.overrideWithValue(prefs)],
      child: const TutomatoApp(),
    ),
  );
}